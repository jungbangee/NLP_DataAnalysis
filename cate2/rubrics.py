WEIGHT_MAP = {"높음": 3, "중간": 2, "낮음": 1}

CATEGORY2_ITEMS = [
    {"id": "2.1", "name": "학습목표 안내",  "weight": "높음"},
    {"id": "2.2", "name": "전날 복습 연계", "weight": "높음"},
    {"id": "2.3", "name": "설명 순서",      "weight": "중간"},
    {"id": "2.4", "name": "핵심내용 강조",  "weight": "중간"},
    {"id": "2.5", "name": "마무리 요약",    "weight": "낮음"},
]


def calc_category_score(scores: dict[str, int]) -> float:
    """
    카테고리 점수 = Σ(score_i × weight_i) / Σ(weight_i)
    C2 = (s21×3 + s22×3 + s23×2 + s24×2 + s25×1) / 11
    """
    total_weighted = 0
    total_weight = 0
    for item in CATEGORY2_ITEMS:
        item_id = item["id"]
        if item_id in scores:
            w = WEIGHT_MAP[item["weight"]]
            total_weighted += scores[item_id] * w
            total_weight += w
    return total_weighted / total_weight if total_weight > 0 else 0.0


def score_to_100(category_score: float) -> float:
    """카테고리 점수(0~5) → 100점 환산"""
    return category_score * 20
